from IPython.display import HTML

class BasicLandscape:
    def __init__(self, size, adjusted_vision=True):
        self.size = size
        self.matrix = np.random.rand(size, size)
        self.vision = np.zeros((size, size))
        self.adjusted_vision = adjusted_vision

    def generate_countdowns(self, num=1):
        return np.random.randint(
            max(1, self.avg_countdown // 2),
            int(self.avg_countdown * 1.5) + 1,
            size=(num, 1)
        )

    def generate_individuals(self, num):
        num = int(num)
        return np.hstack((
            np.random.randint(self.size - 1, size=(num, 2)),
            self.generate_countdowns(num)
        ))

    def set_individual_vision(self, ind):
        x, y = ind[:2]
        size_factor = self.size / 10
        border = int(self.agent_vision * size_factor) if self.adjusted_vision else self.agent_vision
        for xi in range(-border, border + 1):
            for yi in range(-border, border + 1):
                if (0 <= x + xi < self.size) and (0 <= y + yi < self.size) and (xi**2 + yi**2 <= (border + 0.5)**2):
                    self.vision[x + xi, y + yi] = 1


    def animate(self, steps=20, interval=500, save_as=None):
        """Animate the landscape evolution over multiple steps."""
        fig, ax = plt.subplots(subplot_kw={"projection": "3d"})
        m = np.mgrid[:self.size, :self.size]

        def update(frame):
            ax.clear()
            ax.plot_surface(m[0], m[1], self.matrix, cmap='coolwarm', alpha=0.7)
            for ind in self.individuals:
                x, y = ind[:2]
                z = self.matrix[x, y]
                ax.scatter(x, y, z, color='red', s=50)
            ax.set_title(f"Step: {frame + 1}")

            # Perform a simulation step
            self.step()

        anim = FuncAnimation(fig, update, frames=steps, interval=interval, repeat=False)

        if save_as:
            anim.save(save_as, writer='ffmpeg', fps=2)  # Requires ffmpeg installed

        plt.close(fig)  # Close the figure to prevent display in Colab
        return anim  # Return the animation object

    def init_individuals(self, num, avg_countdown=3, agent_vision=1):
        self.avg_countdown = avg_countdown
        self.agent_vision = agent_vision
        self.individuals = self.generate_individuals(num)
        self.accumulated_significance = 0
        self.step_significance_contributions = []
        for ind in self.individuals:
            self.set_individual_vision(ind)

    def plot(self, individuals=False):
        m = np.mgrid[:self.size, :self.size]
        plt.contourf(m[0], m[1], self.matrix, range(self.size * 2), cmap=plt.cm.gray)
        if individuals:
            for ind in self.individuals:
                plt.text(ind[0], ind[1], str(ind[2]))

    def plot_3d(self, individuals=False):
        fig = plt.figure(figsize=(20, 20))
        ax = fig.add_subplot(111, projection='3d')
        m = np.mgrid[:self.size, :self.size]
        ax.plot_surface(m[0], m[1], self.matrix, cmap='coolwarm', alpha=0.7)
        if individuals:
            for ind in self.individuals:
                x, y = ind[:2]
                z = self.matrix[x, y]
                ax.scatter(x, y, z, color='red', s=50)
                ax.text(x, y, z, str(ind[2]), color='black', fontsize=12, weight='bold')
        plt.show()

    def show(self, individuals=False):
        self.plot_3d(individuals=individuals)
        plt.show()

    def save(self, filename, individuals=False):
        self.plot(individuals=individuals)
        plt.colorbar()
        plt.savefig(filename, bbox_inches=0)
        plt.show()

    def plot_vision(self):
        m = np.mgrid[:self.size, :self.size]
        plt.pcolormesh(m[0], m[1], self.vision, cmap=plt.cm.hot)

    def show_vision(self):
        self.plot_vision()
        plt.show()

    def countdown_individual(self, ind):
        ind[2] -= 1
        if ind[2] > 0:
            return ind, -1
        ind[2] = self.generate_countdowns(1)[0, 0]
        ind_z = self.matrix[ind[0], ind[1]]
        self.accumulated_significance += ind_z
        self.step_significance_contributions.append(ind_z)
        return ind, ind_z

    def move_individual(self, ind):
        start_x, start_y = ind[:2]
        max_z = self.matrix[start_x, start_y]
        end_x, end_y = start_x, start_y
        for x_offset in range(-1, 2):
            cur_x = min(self.size - 1, max(0, start_x + x_offset))
            for y_offset in range(-1, 2):
                cur_y = min(self.size - 1, max(0, start_y + y_offset))
                if self.matrix[cur_x, cur_y] > max_z:
                    max_z = self.matrix[cur_x, cur_y]
                    end_x, end_y = cur_x, cur_y
        ind[:2] = end_x, end_y
        self.set_individual_vision(ind)
        return ind

    def step(self):
        for i in range(len(self.individuals)):
            self.individuals[i], ind_z = self.countdown_individual(self.individuals[i])
            if ind_z != -1:
                self.individuals[i] = self.move_individual(self.individuals[i])

