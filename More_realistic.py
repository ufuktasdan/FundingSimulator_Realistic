def save_file(data, filename):
    """
    Save a figure or a DataFrame to a file, creating directories if necessary.

    Parameters:
    data : matplotlib.figure.Figure or pd.DataFrame
        The data to save. This can be a matplotlib figure for PNG files or a pandas DataFrame for CSV files.
    filename : str
        The name of the file where the data will be saved. This should include the path and the file extension.
    """
    # Extract the directory and file extension
    directory = os.path.dirname(filename)
    file_extension = os.path.splitext(filename)[1].lower()

    # Create the directory if it does not exist
    if not os.path.exists(directory):
        os.makedirs(directory)

    # Save the file based on the extension
    if file_extension == '.png':
        if hasattr(data, 'savefig'):
            data.savefig(filename)
        else:
            raise ValueError("Data should be a matplotlib figure for PNG files.")
    elif file_extension == '.csv':
        if isinstance(data, pd.DataFrame):
            data.to_csv(filename, index=False,header=True,mode='a')
        else:
            raise ValueError("Data should be a pandas DataFrame for CSV files.")
    else:
        raise ValueError("Unsupported file extension. Only .png and .csv are supported.")

