import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from tqdm import tqdm
from numpy.random import randint, shuffle

class GaussianLandscape(BasicLandscape):
    def __init__(self, size, num_peaks, max_height, adjusted_vision=True):
        self.adjusted_vision = adjusted_vision
        self.size = size
        self.vision = np.zeros((size, size))
        self.matrix = np.zeros((size, size))
        self.max_height = max_height

        peaks = np.random.randint(1, self.size - 1, size=(int(num_peaks), 3))
        for peak in peaks:
            self.add_gaussian((peak[0], peak[1]), peak[2], np.random.random())

        self.matrix *= max_height / self.matrix.max()

    def add_gaussian(self, loc, sig, height):
        self.matrix += self.get_peak(self.size, loc, (sig, sig), height)

    def get_peak(self, size, loc, sig, max_height):
        m = np.mgrid[:size, :size]
        biv = bivariate_normal(m[0], m[1], sig[0], sig[1], loc[0], loc[1])
        return biv * float(max_height) / biv.max()

    def winner_takes_all(self, ind):
        loc = ind[:2]
        height = -self.matrix[loc[0], loc[1]]
        self.add_gaussian(loc, self.size * 0.01, height)

    def reduced_novelty(self, ind):
        loc = ind[:2]
        height = -0.5 * self.matrix[loc[0], loc[1]]
        self.add_gaussian(loc, self.size * 0.05, height)

    def new_avenue(self):
        loc = np.random.randint(self.size - 1, size=(2,))
        height = np.random.randint(self.matrix.max())
        self.add_gaussian(loc, self.size * 0.06, height)

    def step(self, cutoff=0.7, funding='best', dynamic=True):
        self.step_significance_contributions = []
        indexes_to_move = []

        for i in range(len(self.individuals)):
            self.individuals[i], ind_z = self.countdown_individual(self.individuals[i])
            if ind_z != -1:
                if dynamic and (ind_z / self.matrix.max()) > cutoff:
                    self.reduced_novelty(self.individuals[i])
                    self.new_avenue()
                self.winner_takes_all(self.individuals[i])
                indexes_to_move.append(i)

        for i in indexes_to_move:
            self.individuals[i] = self.move_individual(self.individuals[i])

        if not indexes_to_move:
            self.step_renewal = None
            return

        self._select_candidates(funding, indexes_to_move)

    def _select_candidates(self, funding, indexes_to_move):
        total_individuals = len(self.individuals)
        old_candidates = [self.individuals[i] for i in indexes_to_move]
        self.individuals = np.delete(self.individuals, indexes_to_move, axis=0)

        # Add new candidates until the total number matches
        new_individuals = self.generate_individuals(total_individuals - len(indexes_to_move))

        # Avoid issues with empty arrays during stacking
        if len(old_candidates) > 0:
            old_candidates = np.array(old_candidates)
        else:
            old_candidates = np.empty((0, 3))  # Shape must match the individuals' shape

        if new_individuals.size > 0:
            candidates = np.vstack((old_candidates, new_individuals))
        else:
            candidates = old_candidates  # Use old candidates if no new individuals

        if funding == 'best':
            self._select_best(candidates, len(indexes_to_move))
        elif funding == 'best_visible':
            self._select_best_visible(candidates, len(indexes_to_move))
        elif funding == 'lotto':
            self._select_lotto(candidates, len(indexes_to_move))
        elif funding == 'triage':
            self._select_triage(candidates, indexes_to_move)
        elif funding == 'oldboys':
            self.individuals = np.vstack((self.individuals, old_candidates))
        else:
            raise KeyError(f'Unknown funding option {funding}')


    def _select_best(self, candidates, num_to_select):
        zs = sorted([self.matrix[ind[0], ind[1]] for ind in candidates], reverse=True)[:num_to_select]
        self._select_individuals(candidates, zs)

    def _select_best_visible(self, candidates, num_to_select):
        visible_candidates = [ind for ind in candidates if self.vision[ind[0], ind[1]]]
        zs = sorted([self.matrix[ind[0], ind[1]] for ind in visible_candidates], reverse=True)[:num_to_select]
        self._select_individuals(visible_candidates, zs)

    def _select_lotto(self, candidates, num_to_select):
        np.random.shuffle(candidates)
        selected = candidates[:num_to_select]
        self.individuals = np.vstack((self.individuals, selected))
        for ind in selected:
            self.set_individual_vision(ind)

    def _select_triage(self, candidates, indexes_to_move):
        half = len(indexes_to_move) // 2
        non_visible = [ind for ind in candidates if not self.vision[ind[0], ind[1]]]

        if non_visible:
            np.random.shuffle(non_visible)
            selected_non_visible = np.array(non_visible[:half])
        else:
            selected_non_visible = np.empty((0, self.individuals.shape[1]))  # Ensure correct shape

        for ind in selected_non_visible:
            self.set_individual_vision(ind)

        if selected_non_visible.size > 0:
            self.individuals = np.vstack((self.individuals, selected_non_visible))

        remaining = len(indexes_to_move) - len(selected_non_visible)
        visible = [ind for ind in candidates if self.vision[ind[0], ind[1]]]

        if visible:
            zs = sorted([self.matrix[ind[0], ind[1]] for ind in visible], reverse=True)[:remaining]
            self._select_individuals(visible, zs)


    def _select_individuals(self, candidates, zs):
        count = 0
        for ind in candidates:
            if self.matrix[ind[0], ind[1]] in zs:
                self.individuals = np.vstack((self.individuals, ind))
                self.set_individual_vision(ind)
                count += 1
                if count >= len(zs):
                    break

