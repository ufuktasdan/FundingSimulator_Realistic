    x = np.arange(self.size)
    y = np.arange(self.size)
    X, Y = np.meshgrid(x, y)

    # Calculate radial distance from the peak location
    r = np.sqrt((X - loc[0])**2 + (Y - loc[1])**2)

    # Avoid division by zero for the peak center
    r[r == 0] = 1e-6

    # Calculate the scaling factor 'a' such that the height at r = 0 matches height_at_r0
    a = height_at_r0

    # Calculate the inverse power law
    z = a * r**(-b)

    # Add the peak to the landscape matrix
    self.matrix += z

